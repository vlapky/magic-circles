import type { SymCat } from '../core/config';
import { arc, circle, poly, smooth, type Pt, type Shape } from '../core/ir';

/** Символ в единичном круге: координаты в [-1, 1], верх — отрицательный y. */
export interface Sym {
  id: string;
  cat: SymCat;
  shapes: Shape[];
}

const pairs = (n: number[]): Pt[] => {
  const out: Pt[] = [];
  for (let i = 0; i < n.length; i += 2) out.push([n[i], n[i + 1]]);
  return out;
};
const rad = (d: number): number => (d * Math.PI) / 180;

// Мини-язык описания: c — окружность, d — точка, l — ломаная, p — замкнутый контур,
// s — плавная кривая, a — дуга (градусы, 0° вправо, 90° вниз).
const c = (x: number, y: number, r: number): Shape => circle(x, y, r, 1);
const d = (x: number, y: number, r = 0.11): Shape => circle(x, y, r, 0, 'ink');
const l = (...n: number[]): Shape => poly(pairs(n), 1);
const p = (...n: number[]): Shape => poly(pairs(n), 1, true);
const s = (...n: number[]): Shape => smooth(pairs(n), 1);
const a = (x: number, y: number, r: number, d0: number, d1: number): Shape => arc(x, y, r, rad(d0), rad(d1), 1);

const star = (n: number, k: number, r: number): Shape[] => {
  const pt = (i: number): Pt => [r * Math.sin((i * 2 * Math.PI) / n), -r * Math.cos((i * 2 * Math.PI) / n)];
  const out: Shape[] = [];
  for (let i = 0; i < n; i++) out.push(poly([pt(i), pt(i + k)], 1));
  return out;
};

const O = (): Shape => c(0, 0, 0.82);
const TRI_UP = (): Shape => p(0, -0.8, 0.8, 0.6, -0.8, 0.6);
const TRI_DN = (): Shape => p(0, 0.8, 0.8, -0.6, -0.8, -0.6);

const def = (cat: SymCat, list: Record<string, Shape[]>): Sym[] =>
  Object.entries(list).map(([id, shapes]) => ({ id, cat, shapes }));

