export const LATIN_CHARS = Object.keys(FONT).join('');

const TRANSLIT: Record<string, string> = {
  а: 'A', б: 'B', в: 'V', г: 'G', д: 'D', е: 'E', ё: 'E', ж: 'ZH', з: 'Z', и: 'I', й: 'Y', к: 'K',
  л: 'L', м: 'M', н: 'N', о: 'O', п: 'P', р: 'R', с: 'S', т: 'T', у: 'U', ф: 'F', х: 'H', ц: 'C',
  ч: 'CH', ш: 'SH', щ: 'SCH', ъ: '', ы: 'Y', ь: '', э: 'E', ю: 'YU', я: 'YA',
};

/** Приводит фразу к A–Z, 0–9 и пробелам; кириллица транслитерируется. */
export function toLatin(text: string): string {
  let out = '';
  for (const ch of text.toLowerCase()) {
    if (ch in TRANSLIT) out += TRANSLIT[ch];
    else if (FONT[ch.toUpperCase()]) out += ch.toUpperCase();
    else out += ' ';
  }
  return out.replace(/\s+/g, ' ').trim();
}

const cache = new Map<string, Shape[]>();

export function latinGlyph(ch: string): Shape[] | undefined {
  const def = FONT[ch];
  if (!def) return undefined;
  let g = cache.get(ch);
  if (!g) {
    g = def.split('|').map((stroke) =>
      poly(
        stroke.split(' ').map((p): Pt => {
          const [x, y] = p.split(',').map(Number);
          return [(x / 4 - 0.5) * 0.9, (y / 6 - 0.5) * 1.3];
        }),
        1,
      ),
    );
    cache.set(ch, g);
  }
  return g;
}
